const express = require('express');
const path = require('path');
const crypto = require('crypto');
const fs = require('fs');
const QRCode = require('qrcode');

const app = express();
app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));

const PORT = process.env.PORT || 3000;
const PRICE = 60000;
const MAX_TICKETS = 40;
const MERCHANT_ID = process.env.AIRTEL_MERCHANT_ID || '7217231';
const MERCHANT_NAME = process.env.AIRTEL_MERCHANT_NAME || 'HAKIMU LPSS Roast & Chills';
const ADMIN_PASSWORD = process.env.ADMIN_PASSWORD || '';
const DATA_FILE = path.join(__dirname, 'data', 'tickets.json');

fs.mkdirSync(path.dirname(DATA_FILE), { recursive: true });
if (!fs.existsSync(DATA_FILE)) fs.writeFileSync(DATA_FILE, '[]');

function loadTickets() {
  try { return JSON.parse(fs.readFileSync(DATA_FILE, 'utf8')); }
  catch { return []; }
}
function saveTickets(tickets) {
  const tmp = DATA_FILE + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify(tickets, null, 2));
  fs.renameSync(tmp, DATA_FILE);
}
function id() { return crypto.randomBytes(12).toString('hex'); }
function ticketCode() { return 'RCH-' + crypto.randomBytes(4).toString('hex').toUpperCase(); }
function normalizePhone(input) {
  let p = String(input || '').replace(/[\s-]/g, '');
  if (/^07\d{8}$/.test(p)) return '256' + p.slice(1);
  if (/^7\d{8}$/.test(p)) return '256' + p;
  if (/^2567\d{8}$/.test(p)) return p;
  return null;
}
function publicTicket(t) {
  return { id: t.id, reference: t.reference, code: t.code, name: t.name, phone: t.phone, amount: t.amount, status: t.status, createdAt: t.createdAt, approvedAt: t.approvedAt || null, usedAt: t.usedAt || null, qr: t.qr || null };
}
function adminAuth(req, res, next) {
  const token = req.get('x-admin-token');
  if (!ADMIN_PASSWORD) return res.status(503).json({ error: 'Admin password is not configured.' });
  if (!token || !adminSessions.has(token)) return res.status(401).json({ error: 'Admin login required.' });
  next();
}
const adminSessions = new Set();

app.post('/api/checkout', (req, res) => {
  const { name, phone, quantity = 1 } = req.body || {};
  if (!name || String(name).trim().length < 2) return res.status(400).json({ error: 'Enter the student name.' });
  if (Number(quantity) !== 1) return res.status(400).json({ error: 'One ticket per checkout.' });
  const normalized = normalizePhone(phone);
  if (!normalized) return res.status(400).json({ error: 'Enter a valid Uganda mobile number.' });

  const tickets = loadTickets();
  const approved = tickets.filter(t => t.status === 'PAID' || t.status === 'USED').length;
  if (approved >= MAX_TICKETS) return res.status(409).json({ error: 'All 40 tickets have already been sold.' });

  const existingPending = tickets.find(t => t.phone === normalized && t.status === 'PENDING');
  if (existingPending) return res.json({ pending: true, reference: existingPending.reference });

  const reference = 'RCP-' + crypto.randomBytes(5).toString('hex').toUpperCase();
  const record = {
    id: id(),
    reference,
    code: null,
    name: String(name).trim(),
    phone: normalized,
    amount: PRICE,
    merchantId: MERCHANT_ID,
    merchantName: MERCHANT_NAME,
    status: 'PENDING',
    createdAt: new Date().toISOString(),
    approvedAt: null,
    usedAt: null,
    transactionId: null,
    qr: null
  };
  tickets.push(record);
  saveTickets(tickets);
  res.json({ pending: true, reference, merchantId: MERCHANT_ID, merchantName: MERCHANT_NAME, amount: PRICE });
});

app.post('/api/payment/submit-reference', (req, res) => {
  const { reference, transactionId } = req.body || {};
  const tx = String(transactionId || '').trim();
  if (!reference || !tx) return res.status(400).json({ error: 'Reference and transaction ID are required.' });
  const tickets = loadTickets();
  const t = tickets.find(x => x.reference === String(reference).toUpperCase());
  if (!t) return res.status(404).json({ error: 'Payment submission not found.' });
  if (t.status !== 'PENDING') return res.status(409).json({ error: 'Already processed.' });
  t.transactionId = tx.slice(0, 100);
  saveTickets(tickets);
  res.json({ ok: true });
});

app.get('/api/payment/status/:reference', (req, res) => {
  const tickets = loadTickets();
  const t = tickets.find(x => x.reference === String(req.params.reference).toUpperCase());
  if (!t) return res.status(404).json({ error: 'Reference not found.' });
  res.json({ reference: t.reference, status: t.status, ticket: t.status === 'PAID' || t.status === 'USED' ? publicTicket(t) : null });
});

app.post('/api/admin/login', (req, res) => {
  if (!ADMIN_PASSWORD) return res.status(503).json({ error: 'ADMIN_PASSWORD is not configured.' });
  const password = String(req.body?.password || '');
  const supplied = Buffer.from(password); const expected = Buffer.from(ADMIN_PASSWORD);
  if (supplied.length !== expected.length || !crypto.timingSafeEqual(supplied, expected)) return res.status(401).json({ error: 'Incorrect password.' });
  const token = crypto.randomBytes(32).toString('hex');
  adminSessions.add(token);
  res.json({ token });
});

app.post('/api/admin/logout', adminAuth, (req, res) => {
  adminSessions.delete(req.get('x-admin-token'));
  res.json({ ok: true });
});

app.get('/api/admin/summary', adminAuth, (req, res) => {
  const tickets = loadTickets();
  const paid = tickets.filter(t => t.status === 'PAID' || t.status === 'USED');
  const pending = tickets.filter(t => t.status === 'PENDING');
  const collected = paid.reduce((sum, t) => sum + t.amount, 0);
  res.json({ sold: paid.length, collected, remaining: MAX_TICKETS - paid.length, pending: pending.length });
});

app.get('/api/admin/search', adminAuth, (req, res) => {
  const q = String(req.query.q || '').toLowerCase();
  const tickets = loadTickets();
  const found = tickets.filter(t => !q || [t.name, t.phone, t.reference, t.transactionId, t.code].some(v => String(v || '').toLowerCase().includes(q)));
  res.json(found.map(publicTicket));
});

app.post('/api/admin/approve', adminAuth, async (req, res) => {
  const reference = String(req.body?.reference || '').toUpperCase();
  const tickets = loadTickets();
  const t = tickets.find(x => x.reference === reference);
  if (!t) return res.status(404).json({ error: 'Not found.' });
  t.status = 'PAID';
  t.code = ticketCode();
  t.approvedAt = new Date().toISOString();
  t.qr = await QRCode.toDataURL(t.code, { margin: 1, width: 320 });
  saveTickets(tickets);
  res.json({ ok: true, ticket: publicTicket(t) });
});

app.post('/api/admin/reject', adminAuth, (req, res) => {
  const reference = String(req.body?.reference || '').toUpperCase();
  const tickets = loadTickets();
  const t = tickets.find(x => x.reference === reference);
  if (!t) return res.status(404).json({ error: 'Not found.' });
  t.status = 'REJECTED';
  saveTickets(tickets);
  res.json({ ok: true });
});

app.post('/api/admin/verify', adminAuth, (req, res) => {
  const code = String(req.body?.code || '').trim().toUpperCase();
  const tickets = loadTickets();
  const t = tickets.find(x => x.code === code);
  if (!t) return res.json({ valid: false, message: 'Ticket not found.' });
  if (t.status === 'USED') return res.json({ valid: false, message: 'Ticket already used.' });
  if (t.status !== 'PAID') return res.json({ valid: false, message: 'Ticket not active.' });
  res.json({ valid: true, ticket: publicTicket(t), message: 'Valid ticket!' });
});

app.post('/api/admin/use', adminAuth, (req, res) => {
  const code = String(req.body?.code || '').trim().toUpperCase();
  const tickets = loadTickets();
  const t = tickets.find(x => x.code === code);
  if (!t) return res.status(404).json({ error: 'Ticket not found.' });
  t.status = 'USED';
  t.usedAt = new Date().toISOString();
  saveTickets(tickets);
  res.json({ ok: true });
});

app.get('/health', (req, res) => res.status(200).json({ ok: true }));

app.listen(PORT, '0.0.0.0', () => console.log(`Server running on port ${PORT}`));
